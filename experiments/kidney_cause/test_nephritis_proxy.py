import os
import sys

import numpy as np
import pandas as pd
import pytest
import joblib

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import nephritis_proxy as NP
import make_report as MR


def test_schema_rejects_missing_and_unexpected_features():
    with pytest.raises(ValueError, match="Missing model features"):
        NP.validate_input(pd.DataFrame({"a": [1]}), ["a", "b"])
    with pytest.raises(ValueError, match="Unexpected model features"):
        NP.validate_input(pd.DataFrame({"a": [1], "b": [2]}), ["a"])


def test_threshold_is_selected_from_supplied_development_predictions():
    y = np.array([0, 0, 0, 1, 1, 1])
    probability = np.array([0.1, 0.2, 0.4, 0.35, 0.8, 0.9])
    threshold = NP.choose_threshold(y, probability)
    assert NP._metrics(y, probability, threshold)["balanced_accuracy"] == pytest.approx(5 / 6)


def test_repeated_outer_splits_predict_every_patient_once_per_repeat():
    rng = np.random.default_rng(7)
    X = rng.normal(size=(60, 3))
    y = np.repeat([0, 1], 30)
    result = NP.repeated_nested_evaluation(
        X, y, np.arange(60), names=("LR",), seed=11, repeats=2, outer_folds=3,
    )["LR"]
    assert len(result["split_metrics"]) == 6
    assert len(result["predictions"]) == 60
    assert {row["SEQN"] for row in result["predictions"]} == set(range(60))


def test_packaged_model_loads_and_enforces_feature_order():
    path = os.path.join(HERE, "models", "immune_kidney_proxy.joblib")
    if not os.path.exists(path):
        pytest.skip("packaged model is generated by nephritis_proxy.py")
    bundle = joblib.load(path)
    frame = pd.DataFrame([{feature: np.nan for feature in bundle["features"]}])
    prediction = NP.predict_bundle(bundle, frame)
    assert list(prediction) == ["probability_immune_proxy", "positive_at_locked_threshold"]
    assert prediction["probability_immune_proxy"].between(0, 1).all()


def test_report_auc_triplet_comes_from_result_data():
    block = {"models": {"HGB": {"ovr_auc": {
        "免疫性": {"auc": 0.1}, "感染性": {"auc": 0.2}, "代謝性": {"auc": 0.3},
    }}}}
    assert MR.auc_triplet(block) == [0.1, 0.2, 0.3]
